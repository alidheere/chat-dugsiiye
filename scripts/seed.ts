async function seedDatabase() {
  try {
    await connectDB();

    // Clear old test data
    await Movie.deleteMany({});
    await User.deleteMany({});

    const movies = movieData.map(
      ([title, year, genre, rating, director]) => ({
        title,
        year,
        genre,
        rating,
        director,
        description: `${title} is a ${genre} movie released in ${year}.`,
      })
    );

    const users = userData.map(
      ([name, email, age, favorite_genre]) => ({
        name,
        email,
        age,
        favorite_genre,
      })
    );

    await Movie.insertMany(movies);
    await User.insertMany(users);

    console.log("Database seeded successfully!");
    console.log(`Movies added: ${movies.length}`);
    console.log(`Users added: ${users.length}`);
  } catch (error) {
    console.error("Seeding failed:", error);
  } finally {
    await import("mongoose").then(({ default: mongoose }) =>
      mongoose.disconnect()
    );
  }
}

seedDatabase();
